
import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
await fs.mkdir('qa',{recursive:true});
const browser = await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page = await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
const response=await page.goto('http://localhost:4321/',{waitUntil:'networkidle'});
assert.equal(response.status(),200);
await page.evaluate(async()=>{document.documentElement.style.scrollBehavior='auto';document.querySelectorAll('img').forEach(img=>img.loading='eager');await Promise.all([...document.images].map(img=>img.decode().catch(()=>{})));await document.fonts.ready;});
for(const width of [320,390,768,1440]){
 await page.setViewportSize({width,height:width===1440?1000:844});
 await page.evaluate(async()=>{for(let y=0;y<document.body.scrollHeight;y+=700){window.scrollTo(0,y);await new Promise(r=>setTimeout(r,35));}window.scrollTo(0,0);});
 await page.waitForTimeout(250);
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Horizontal overflow at '+width);
 await page.screenshot({path:'qa/'+width+'-full.png',fullPage:true});
 const broken=await page.locator('main img').evaluateAll(imgs=>imgs.filter(img=>!img.complete||img.naturalWidth===0).map(img=>img.src));
 assert.deepEqual(broken,[],'Broken photos at '+width);
}
await page.setViewportSize({width:390,height:844});
await page.getByRole('button',{name:'Open navigation'}).click();
await page.locator('#mobile-menu').getByRole('link',{name:'Our work'}).click();
assert.equal(await page.locator('#mobile-menu').isVisible(),false);
await page.getByRole('button',{name:'Baby',exact:true}).click();
assert.equal(await page.locator('.gallery-item:visible').count(),1);
await page.locator('.gallery-item:visible').click();
assert(await page.locator('#lightbox').isVisible());
await page.keyboard.press('ArrowRight');
assert.equal(await page.locator('#lightbox-count').textContent(),'1 / 1');
await page.keyboard.press('Escape');
assert.equal(await page.locator('#lightbox').isVisible(),false);
await page.getByRole('button',{name:'Corporate',exact:true}).click();
assert(await page.locator('.gallery-empty').isVisible());
await page.getByRole('button',{name:'All moments',exact:true}).click();
assert.equal(await page.locator('.gallery-item:visible').count(),6);
await page.locator('.gallery-item').first().click();
await page.keyboard.press('ArrowRight');
assert.equal(await page.locator('#lightbox-count').textContent(),'2 / 6');
await page.getByRole('button',{name:'Close photograph',exact:true}).click();
await page.getByRole('button',{name:'Next testimonial',exact:true}).click();
assert.match(await page.locator('.review-slide:visible').innerText(),/parents and grandparents/);
await page.getByRole('button',{name:'Previous testimonial',exact:true}).click();
await page.locator('#name').fill('Test Visitor');
await page.locator('#phone').fill('+++++++');
await page.locator('#occasion').selectOption('Wedding');
await page.locator('.form-submit').click();
assert.equal(await page.locator('#phone').evaluate(el=>el.validity.valid),false);
await page.locator('#phone').fill('+91 98765 43210');
await page.locator('#message').fill('A wedding in Nellore. Please share availability.');
await page.evaluate(()=>{window.open=(url)=>{window.__testWhatsApp=String(url);return null;};});
await page.locator('.form-submit').click();
const url=await page.evaluate(()=>window.__testWhatsApp);
assert(url.startsWith('https://wa.me/919908996227?text='));
const message=new URL(url).searchParams.get('text');
assert(message.includes('Test Visitor')&&message.includes('Wedding')&&message.includes('Nellore'));
assert(await page.locator('#form-status a').isVisible());
const events=await page.evaluate(()=>window.dataLayer);
assert.equal(events.at(-1).event,'bharani_enquiry_intent');
assert(!JSON.stringify(events).includes('98765'));
await page.getByRole('button',{name:'Privacy',exact:true}).click();
assert(await page.locator('#privacy').isVisible());
await page.keyboard.press('Escape');
assert.equal(await page.locator('#privacy').isVisible(),false);
assert.deepEqual(errors,[],'Browser errors');
await fs.writeFile('qa/results.json',JSON.stringify({passed:true,viewports:[320,390,768,1440],checks:['No horizontal overflow','All photographs loaded','Mobile navigation','Gallery category filters and corporate empty state','Lightbox navigation, Escape and focus restoration','Testimonial controls','Phone validation','WhatsApp message preparation without sending','No personal details in analytics event','Privacy dialog'],browserErrors:errors},null,2));
await browser.close();
console.log('PASS: responsive, image, gallery, navigation, testimonial, form and privacy checks.');
